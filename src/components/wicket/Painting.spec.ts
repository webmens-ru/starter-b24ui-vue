async function choosePaint(w: VueWrapper, id: string): Promise<void> {
 const data = vi.mocked(getColorShield).mock.results.slice().reverse().find(result => result.type === 'return')
 if (!data) throw new Error('Catalog has not loaded')
 const response = await data.value
 const item = response.colorShield.find((paint: PaintItem) => paint.id === Number(id)) as PaintItem
 if (item.isFixedColor && !item.isCustomerSupplied) {
  await w.get('[data-paint-category="30"]').trigger('click')
  const colorId = item.colors.find(color => color.id === useCalculation().paintColorId.value)?.id ?? item.colors[0]?.id
  await w.get(`[data-paint-row="${id}:${colorId}"]`).trigger('click')
 } else {
  if (!w.find('[data-testid="paint-product"]').exists()) await w.get(`[data-paint-category="${item.paintCategoryId}"]`).trigger('click')
  await w.get('[data-testid="paint-product"]').setValue(id)
 }
}
